#!/usr/bin/env python3
"""The MS-DOS screen's side panels (src/msdos/margins.txt) as a C header.

Usage:
    margins_msdos.py MARGINS.txt [TITLE.atascii] > margins.h

MARGINS.txt is the 80 x 25 screen as it shows, in UTF-8: 25 lines of at most 80
characters, any character code page 437 has (box drawing, blocks, the symbols
of codes 01-1F such as ○ and ■). Columns 0-18 are the left panel and 61-79 the
right; columns 19-60 must be blank (the 40-column game window and a gutter on
each side of it). The header has margins[25][38]: each row's left panel, then its
right, in code page 437.

With TITLE.atascii (the Atari's logo), also the 80-column title screen's: the logo doubled over the board, as
tools/board80.py makes it. src/msdos/display_text.c doubles title_art[] itself (TITLE80_SHIFT columns right of
twice each column), so the header has only title_margins[TITLE80_ROWS][38]: the panels of the rows the clearing
changed, which the title screen draws in place of margins'."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import board80  # noqa: E402

LEFT, RIGHT, WIDTH = 19, 61, 19
# code page 437's glyphs for codes 01-1F and 7F, which Python's cp437 codec reads as control characters
LOW = "☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"


def cp437(ch, where):
    if ch in LOW:
        return LOW.index(ch) + 1
    if ch == "⌂":
        return 0x7F
    try:
        b = ch.encode("cp437")[0]
    except UnicodeEncodeError:
        sys.exit("%s: %r is not in code page 437" % (where, ch))
    if b < 0x20 and ch != " ":
        sys.exit("%s: %r is a control character" % (where, ch))
    return b


def table(name, rows):
    print("static const unsigned char %s[%d][%d] = {     /* each row: the left panel, then the right */"
          % (name, len(rows), 2 * WIDTH))
    for r, row in enumerate(rows):
        where = "%s row %d" % (name, r)
        print("    { " + ", ".join("0x%02X" % cp437(ch, where) for ch in row[:WIDTH] + row[RIGHT:]) + " },")
    print("};")


def main():
    path = sys.argv[1]
    lines = open(path, encoding="utf-8").read().rstrip("\n").split("\n")
    if len(lines) != 25:
        sys.exit("%s: %d lines, must be 25" % (path, len(lines)))
    rows = []
    for r, line in enumerate(lines):
        if len(line) > 80:
            sys.exit("%s:%d: %d characters, at most 80" % (path, r + 1, len(line)))
        line = line.ljust(80)
        if line[LEFT:RIGHT].strip():
            sys.exit("%s:%d: columns 19-60 must be blank (the game window and its gutters)" % (path, r + 1))
        where = "%s:%d" % (path, r + 1)
        rows.append(list(line))
    print("/* Generated by tools/margins_msdos.py from %s: don't edit. */" % " and ".join(sys.argv[1:]))
    table("margins", rows)
    if len(sys.argv) > 2:
        logo, shift = board80.logo_shift(sys.argv[2])
        if len(logo) > 14:
            sys.exit("%s: the logo has %d rows, at most 14" % (sys.argv[2], len(logo)))
        title = board80.cleared(rows, board80.logo_rows(sys.argv[2]))
        changed = [r for r in range(25) if title[r] != rows[r]]
        n = changed[-1] + 1 if changed else 0
        table("title_margins", title[:n])
        print("#define TITLE80_ROWS %d               /* the rows of title_margins */" % n)
        print("#define TITLE80_SHIFT %d              /* the 80-column logo: a cell at column c of title_art goes "
              "at 2c + this */" % shift)
    print("#define MARGIN_W %d                  /* each panel's width; the right one starts at column %d */"
          % (WIDTH, RIGHT))


if __name__ == "__main__":
    main()
