"""Throwaway mockups of the Amiga client: 320x256 low-res, 32 colours (12-bit), an 8x8 bitmap font.
Every colour is a 4-bit-per-channel Amiga colour; the title's backdrop gradient is COLOR0 changed by the Copper."""
import os, re, sys, tomllib
from PIL import Image

W, H = 320, 256
FONT = {}


def load_font(path):
    code = None
    rows = []
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"^0x([0-9A-Fa-f]{2})\b", line)
        if m:
            code, rows = int(m.group(1), 16), []
            continue
        if code is not None and re.fullmatch(r"[#.]{8}", line):
            rows.append(line)
            if len(rows) == 8:
                FONT[code] = rows
                code = None


def rgb(h):  # "f3c" -> Amiga 12-bit colour as 8-bit RGB (x17)
    return tuple(int(c, 16) * 17 for c in h)


# ---- the syndicates come from the theme (letter and short name, in id order)
THEME = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "theme", "theme.toml")
SYN = [(t["letter"], t["short"]) for t in tomllib.load(open(THEME, "rb"))["syndicate"]]

# ---- the 32-colour palette. The base colours by name; a syndicate's bright colour is P[letter], its dim P[letter + "d"].
BASE = dict(
    bg0="001", bg1="012", bg2="123", edge="346", edgehi="69a", text="dde", dim="889", white="fff",
    cyan="3df", amber="fb2", red="f33", green="3f8", steel="9ab", steel2="567", mag="f3c",
)
SYN_BRIGHT = ["4bc", "b85", "a6e", "9b4", "f45", "3c8", "fd3"]     # in syndicate id order
SYN_DIM = ["267", "643", "538", "463", "823", "164", "971"]
POINTER_COLOURS = ["000", "f80", "fff"]                             # sprite colour registers 17-19
P = dict(BASE)
for (_letter, _), _b, _d in zip(SYN, SYN_BRIGHT, SYN_DIM):
    P[_letter] = _b
    P[_letter + "d"] = _d

# Register order. The SYN pens are contiguous (7 bright) and so are the dim (7), 12 apart, round the three sprite registers.
REGS = (["bg0", "text", "dim", "white", "bg1", "bg2", "edge", "edgehi"]
        + [l for l, _ in SYN] + ["cyan", "amber"] + ["@sprite"] * 3
        + [l + "d" for l, _ in SYN] + ["red", "green", "steel", "steel2", "mag"])
assert len(REGS) == 32


def header():
    """src/amiga/palette.h: the registers, and a PEN_ name for each."""
    out = ["/* GENERATED by tools/amiga_mock.py --header: the Amiga client's 32 colours (12-bit 0x0RGB). Do not edit. */",
           "#ifndef AMIGA_PALETTE_H", "#define AMIGA_PALETTE_H", "",
           "/* syndicates: " + "".join(l for l, _ in SYN) + " (bright pens PEN_SYN + id, dim PEN_SYN_DIM + id) */", "",
           "static const unsigned short amiga_palette[32] = {"]
    sprite = iter(POINTER_COLOURS)
    for n, name in enumerate(REGS):
        col = next(sprite) if name == "@sprite" else P[name]
        out.append("    0x0%s,  /* %d %s */" % (col.upper(), n, "pointer" if name == "@sprite" else name))
    out.append("};")
    out.append("")
    for n, name in enumerate(REGS):
        if name.startswith("@"):
            continue
        if name in dict(SYN) or (name.endswith("d") and name[:-1] in dict(SYN)):
            continue
        out.append("#define PEN_%-8s %d" % (name.upper(), n))
    out.append("#define PEN_%-8s %d" % ("SYN", REGS.index(SYN[0][0])))
    out.append("#define PEN_%-8s %d" % ("SYN_DIM", REGS.index(SYN[0][0] + "d")))
    out.append("#define PEN_%-8s %d" % ("SPRITE", REGS.index("@sprite")))
    out += ["", "#endif", ""]
    return "\n".join(out)


class Canvas:
    def __init__(self):
        self.im = Image.new("RGB", (W, H), rgb(P["bg0"]))
        self.px = self.im.load()

    def c(self, k):
        return rgb(P[k]) if isinstance(k, str) and k in P else k

    def rect(self, x, y, w, h, k):
        col = self.c(k)
        for j in range(max(0, y), min(H, y + h)):
            for i in range(max(0, x), min(W, x + w)):
                self.px[i, j] = col

    def frame(self, x, y, w, h, k):
        self.rect(x, y, w, 1, k); self.rect(x, y + h - 1, w, 1, k)
        self.rect(x, y, 1, h, k); self.rect(x + w - 1, y, 1, h, k)

    def bevel(self, x, y, w, h, fill, hi="edgehi", lo="bg0"):
        self.rect(x, y, w, h, fill)
        self.rect(x, y, w, 1, hi); self.rect(x, y, 1, h, hi)
        self.rect(x, y + h - 1, w, 1, lo); self.rect(x + w - 1, y, 1, h, lo)

    def text(self, x, y, s, k, scale=1, shadow=None):
        col = self.c(k)
        if shadow:
            self.text(x + scale, y + scale, s, shadow, scale)
        for ch in s:
            g = FONT.get(ord(ch), FONT[0x20])
            for j, row in enumerate(g):
                for i, b in enumerate(row):
                    if b == "#":
                        self.rect(x + i * scale, y + j * scale, scale, scale, col)
            x += 8 * scale
        return x

    def line(self, x0, y0, x1, y1, k):
        col = self.c(k)
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            if 0 <= x0 < W and 0 <= y0 < H:
                self.px[x0, y0] = col
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy: err += dy; x0 += sx
            if e2 <= dx: err += dx; y0 += sy

    def save(self, name, scale=3):
        self.im.resize((W * scale, H * scale), Image.NEAREST).save(name)
        return self.im

    def ncolors(self):
        return len(set(self.im.getdata()))


