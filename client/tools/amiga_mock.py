def backdrop_gradient(cv, top="001", bot="024"):
    a, b = rgb(top), rgb(bot)
    for y in range(H):
        t = y / (H - 1)
        col = tuple(round((a[i] + (b[i] - a[i]) * t) / 17) * 17 for i in range(3))
        for x in range(W):
            if cv.px[x, y] == rgb("001"):
                cv.px[x, y] = col


