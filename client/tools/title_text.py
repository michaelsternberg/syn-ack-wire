#!/usr/bin/env python3
"""The Apple II title logo (apple2_text) from a plain text file, as a C header.

Usage:
    title_text.py TITLE.txt > title_art.h

TITLE.txt is the logo as it shows, from screen row 0: at most 24 lines of at
most 40 characters, printable ASCII ($20-$7E: the IIe, IIc and IIgs have the
lower-case glyphs, | among them, in normal video). Leading and trailing blanks
are not stored. The header has title_art[]: for each line with something on it,
its row, its column, its length and its characters as screen codes (normal
video), ending in $FF; and TITLE_END, the last row the logo uses."""
import sys


def main():
    lines = open(sys.argv[1]).read().rstrip("\n").split("\n")
    if len(lines) > 24:
        sys.exit("%s: %d lines, at most 24" % (sys.argv[1], len(lines)))
    out, end = [], 0
    for r, line in enumerate(lines):
        line = line.rstrip()
        if len(line) > 40:
            sys.exit("%s:%d: %d characters, at most 40" % (sys.argv[1], r + 1, len(line)))
        bad = [ch for ch in line if not " " <= ch <= "~"]
        if bad:
            sys.exit("%s:%d: %r is not printable ASCII" % (sys.argv[1], r + 1, bad[0]))
        body = line.lstrip()
        if body:
            c = len(line) - len(body)
            out.append([r, c, len(body)] + [ord(ch) | 0x80 for ch in body])
            end = r
    print("/* Generated by tools/title_text.py from %s: don't edit. */" % sys.argv[1])
    print("static const unsigned char title_art[] = {")
    for rec in out:
        print("    " + ", ".join(str(b) for b in rec) + ",")
    print("    0xFF")
    print("};")
    print("#define TITLE_END %d" % end)


if __name__ == "__main__":
    main()
