#!/usr/bin/env python3
"""Turn the title art (an ATASCII file, $9B ends a line) into the Atari client's title data.

The art draws block letters as outlines: a letter's strokes are the spaces inside the
box-drawing lines. Those spaces get the static (snow.s): four quad-width players side by
side, one bit a character, so the strokes must fit in 32 columns.

Usage:
    title_art.py c ROW ART      C header: the art for screen rows from ROW (display_text.c)
    title_art.py s ROW ART      ca65 include: the players' masks (snow.s)
    title_art.py d ROW ART      C header for MS-DOS: the same art in code page 437's box characters
                                (src/msdos/display_text.c, the Apple II header's format)
    title_art.py k ROW ART FONT C header for the CoCo: the art in the box glyphs of FONT (src/coco/font.txt,
                                codes from $60), in the MS-DOS header's format
    title_art.py m ROW ART FONT C header for the CoCo's static (src/coco/snow.c): which pixels of each line
                                get it, and a table of random bytes
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import font_coco  # noqa: E402

BOTTOM = {0x12, 0x18, 0x1A, 0x03, 0x20}     # ─ ┴ └ ┘ and space: a row that closes its letters
PLAYERS = 4


def load(path):
    lines = open(path, "rb").read().split(b"\x9b")
    while lines and not lines[-1].strip():
        lines.pop()
    return [l.ljust(40, b" ")[:40] for l in lines]


def bands(art):
    """The rows of each line of letters: a band ends with its bottom outline."""
    start = 0
    for r, line in enumerate(art):
        if line.strip() and set(line) <= BOTTOM:
            yield range(start, r + 1)
            start = r + 1
    if start < len(art):
        yield range(start, len(art))


def strokes(art):
    """The spaces enclosed by each band's outline, as (row, column) pairs."""
    inside = set()
    for band in bands(art):
        cells = {(r, c) for r in band for c in range(40) if art[r][c] == 0x20}
        edge = [(r, c) for r, c in cells if r in (band[0], band[-1]) or c in (0, 39)]
        out = set()
        while edge:
            r, c = edge.pop()
            if (r, c) in out:
                continue
            out.add((r, c))
            edge += [n for n in ((r + 1, c), (r - 1, c), (r, c + 1), (r, c - 1)) if n in cells]
        inside |= cells - out
    return inside


def screen(b):
    """ATASCII to the internal code screen memory holds."""
    c = b & 0x7F
    return (c + 0x40 if c < 0x20 else c - 0x20 if c < 0x60 else c) | (b & 0x80)


def c_header(art, row):
    out = ["/* generated by tools/title_art.py: the title art, drawn from screen row %d */" % row,
           "#define TITLE_END %d          /* the first row below it */" % (row + len(art)),
           "#define SNOW_LEFT %d          /* player 0's horizontal position */" % (48 + 4 * left(art)),
           "static const unsigned char title_art[] = {   /* row, column, length, screen codes */"]
    for r, line in enumerate(art):
        text = line.rstrip(b" ")
        col = len(text) - len(text.lstrip(b" "))
        if text:
            out.append("    %d, %d, %d, %s," % (row + r, col, len(text) - col,
                                               ", ".join("0x%02X" % screen(b) for b in text[col:])))
    out += ["    0xFF", "};"]
    return "\n".join(out)


def left(art):
    return min(c for _, c in strokes(art))


def s_include(art, row):
    inside = strokes(art)
    rows = sorted({r for r, _ in inside})
    first, last = rows[0], rows[-1]
    c0 = left(art)
    if max(c for _, c in inside) - c0 >= 8 * PLAYERS:
        sys.exit("title_art.py: the letters are wider than %d columns" % (8 * PLAYERS))
    n = last - first + 1
    if 4 * n > 128:
        sys.exit("title_art.py: the letters are taller than 32 rows")
    out = ["; generated by tools/title_art.py: which characters of each text row get the static",
           "SNOW_TOP  = %d          ; player byte of the first row: 2 scan lines a byte, row 0 at byte 16"
           % (16 + 4 * (row + first)),
           "SNOW_ROWS = %d" % n,
           "snow_mask:              ; player 0's rows, then player 1's, ...; bit 7 = its left column"]
    for p in range(PLAYERS):
        masks = []
        for r in range(first, last + 1):
            m = 0
            for b in range(8):
                if (r, c0 + 8 * p + b) in inside:
                    m |= 0x80 >> b
            masks.append("$%02X" % m)
        out.append("        .byte " + ", ".join(masks))
    return "\n".join(out)


# ATASCII to code page 437: the box characters are the same; the two quarter blocks the logo's
# hyphen is made of (top-left, top-right) have no match, and become upper half blocks.
CP437 = {0x20: 0x20, 0x7C: 0xB3, 0x12: 0xC4, 0x01: 0xC3, 0x04: 0xB4, 0x11: 0xDA, 0x05: 0xBF,
         0x1A: 0xC0, 0x03: 0xD9, 0x17: 0xC2, 0x18: 0xC1, 0x13: 0xC5, 0x0C: 0xDF, 0x0B: 0xDF}


def d_header(art, row):
    out = ["/* generated by tools/title_art.py d: the Atari's title art in code page 437, from screen row %d */"
           % row, "static const unsigned char title_art[] = {   /* row, column, length, characters */"]
    end = row
    for r, line in enumerate(art):
        text = line.rstrip(b" ")
        col = len(text) - len(text.lstrip(b" "))
        if not text:
            continue
        bad = [b for b in text if b not in CP437]
        if bad:
            sys.exit("title_art.py: ATASCII $%02X on art line %d has no code page 437 character" % (bad[0], r + 1))
        out.append("    %d, %d, %d, %s," % (row + r, col, len(text) - col,
                                           ", ".join("0x%02X" % CP437[b] for b in text[col:])))
        end = row + r
    out += ["    0xFF", "};", "#define TITLE_END %d          /* the last row it uses */" % end]
    return "\n".join(out)


# ATASCII to the CoCo's box glyphs (font.txt, from $60); both halves of the hyphen are one block.
COCO = {0x20: 0x20, 0x12: 0x60, 0x7C: 0x61, 0x11: 0x62, 0x05: 0x63, 0x1A: 0x64, 0x03: 0x65, 0x17: 0x66,
        0x18: 0x67, 0x01: 0x68, 0x04: 0x69, 0x0B: 0x6A, 0x0C: 0x6A}
SNOW_GAP = 2            # the static keeps this many pixels clear of the lines, so they stand out of it
SNOW_DENSITY = 0.3      # the share of its pixels lit


def coco_codes(art):
    for r, line in enumerate(art):
        bad = [b for b in line if b not in COCO]
        if bad:
            sys.exit("title_art.py: ATASCII $%02X on art line %d has no CoCo box glyph" % (bad[0], r + 1))
    return [[COCO[b] for b in line] for line in art]


def k_header(art, row, font):
    codes = coco_codes(art)
    out = ["/* generated by tools/title_art.py k: the Atari's title art in the CoCo's box glyphs (font.txt), "
           "from screen row %d */" % row,
           "static const unsigned char title_art[] = {   /* row, column, length, codes */"]
    end = row
    for r, line in enumerate(codes):
        text = bytes(line).rstrip(b" ")
        col = len(text) - len(text.lstrip(b" "))
        if not text:
            continue
        out.append("    %d, %d, %d, %s," % (row + r, col, len(text) - col,
                                           ", ".join("0x%02X" % b for b in text[col:])))
        end = row + r
    out += ["    0xFF", "};", "#define TITLE_END %d          /* the last row it uses */" % end]
    return "\n".join(out)


def snow_pixels(art, row, font):
    """The pixels that get the static, as a set of (y, x): the letters' strokes, out to their outline
    (a flood fill from the stroke cells that the lines and the spaces outside the letters stop), less
    SNOW_GAP pixels around the lines. Cell (r, c) is pixels 8 + 6c, 8r as src/coco/text.c draws it."""
    box = {code: rows for code, _, rows in font_coco.read_box(font)}
    codes = coco_codes(art)
    inside = strokes(art)
    line, wall, fill = set(), set(), []
    for r, l in enumerate(codes):
        for c, b in enumerate(l):
            x0, y0 = 8 + 6 * c, 8 * (row + r)
            cell = [(y0 + y, x0 + x) for y in range(8) for x in range(6)]
            if b != 0x20:
                line |= {(y0 + y, x0 + x) for y in range(8) for x in range(6) if box[b][y][x] == "#"}
            elif (r, c) in inside:
                fill += cell
            else:
                wall |= set(cell)
    wall |= line
    filled = set(fill)
    while fill:
        y, x = fill.pop()
        for n in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
            if n not in filled and n not in wall and 0 <= n[0] < 192 and 0 <= n[1] < 256:
                filled.add(n)
                fill.append(n)
    near = set(line)
    for _ in range(SNOW_GAP):
        near |= {(y + dy, x + dx) for y, x in near for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1))}
    return filled - near


def m_header(art, row, font):
    px = snow_pixels(art, row, font)
    top = min(y for y, _ in px)
    bottom = max(y for y, _ in px)
    recs, index, data = {}, [], []
    for y in range(top, bottom + 1):
        masks = [sum(0x80 >> b for b in range(8) if (y, 8 * k + b) in px) for k in range(32)]
        rec, k = [], 0
        while k < 32:
            if masks[k] == 0:
                n = k
                while k < 32 and masks[k] == 0:
                    k += 1
                if k < 32:
                    rec.append(0x40 + k - n)
                continue
            n = k
            if masks[k] == 0xFF:
                while k < 32 and masks[k] == 0xFF:
                    k += 1
                rec.append(0x80 + k - n)
            else:
                while k < 32 and masks[k] not in (0, 0xFF):
                    k += 1
                rec += [k - n] + masks[n:k]
        rec = tuple(rec + [0])
        if rec not in recs:
            recs[rec] = len(data)
            data += rec
        index.append(list(recs).index(rec))
    if len(recs) > 256:
        sys.exit("title_art.py: over 256 kinds of line in the static")
    rnd = random.Random(1)
    table = [sum(0x80 >> b for b in range(8) if rnd.random() < SNOW_DENSITY) for _ in range(256)]
    out = ["/* generated by tools/title_art.py m: the title's static (snow.c), from screen row %d */" % row,
           "#define SNOW_TOP   %d     /* its first pixel line */" % top,
           "#define SNOW_LINES %d    /* and how many */" % (bottom - top + 1),
           "/* each line's record (as snow.c reads it): $01-$3F that many bytes masked, the masks",
           " * following; $40-$7F skip n - $40 bytes; $80-$FF n - $80 bytes all static; $00 the end */",
           "static const unsigned char snow_rec[] = {"]
    for rec in recs:
        out.append("    %s," % ", ".join("0x%02X" % b for b in rec))
    out += ["};", "static const unsigned snow_at[%d] = {   /* where each record starts */" % len(recs)]
    out.append("    %s" % ", ".join(str(v) for v in recs.values()))
    out += ["};", "static const unsigned char snow_line[SNOW_LINES] = {   /* each line's record */"]
    for i in range(0, len(index), 16):
        out.append("    %s," % ", ".join(str(v) for v in index[i:i + 16]))
    out += ["};", "static const unsigned char snow_rand[256] = {   /* %d%% of the bits set */"
            % round(100 * SNOW_DENSITY)]
    for i in range(0, 256, 16):
        out.append("    %s," % ", ".join("0x%02X" % v for v in table[i:i + 16]))
    out.append("};")
    return "\n".join(out)


def main():
    if sys.argv[1:2] in (["k"], ["m"]):
        if len(sys.argv) != 5:
            sys.exit(__doc__)
    elif len(sys.argv) != 4 or sys.argv[1] not in ("c", "s", "d"):
        sys.exit(__doc__)
    art = load(sys.argv[3])
    row = int(sys.argv[2])
    if row + len(art) > 24:
        sys.exit("title_art.py: the art runs off the screen")
    if sys.argv[1] in ("k", "m"):
        print({"k": k_header, "m": m_header}[sys.argv[1]](art, row, sys.argv[4]))
    else:
        print({"c": c_header, "s": s_include, "d": d_header}[sys.argv[1]](art, row))


main()
