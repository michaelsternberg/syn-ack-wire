#!/usr/bin/env python3
"""Turn the title art (an ATASCII file, $9B ends a line) into the Atari client's title data.

The art draws block letters as outlines: a letter's strokes are the spaces inside the
box-drawing lines. Those spaces get the static (snow.s): four quad-width players side by
side, one bit a character, so the strokes must fit in 32 columns.

Usage:
    title_art.py c ROW ART      C header: the art for screen rows from ROW (display_text.c)
    title_art.py s ROW ART      ca65 include: the players' masks (snow.s)
"""
import sys

BOTTOM = {0x12, 0x18, 0x1A, 0x03, 0x20}     # ─ ┴ └ ┘ and space: a row that closes its letters
PLAYERS = 4


def load(path):
    lines = open(path, "rb").read().split(b"\x9b")
    while lines and not lines[-1].strip():
        lines.pop()
    return [l.ljust(40, b" ")[:40] for l in lines]


def bands(art):
    """The rows of each line of letters: a band ends with its bottom outline."""
    start = 0
    for r, line in enumerate(art):
        if line.strip() and set(line) <= BOTTOM:
            yield range(start, r + 1)
            start = r + 1
    if start < len(art):
        yield range(start, len(art))


def strokes(art):
    """The spaces enclosed by each band's outline, as (row, column) pairs."""
    inside = set()
    for band in bands(art):
        cells = {(r, c) for r in band for c in range(40) if art[r][c] == 0x20}
        edge = [(r, c) for r, c in cells if r in (band[0], band[-1]) or c in (0, 39)]
        out = set()
        while edge:
            r, c = edge.pop()
            if (r, c) in out:
                continue
            out.add((r, c))
            edge += [n for n in ((r + 1, c), (r - 1, c), (r, c + 1), (r, c - 1)) if n in cells]
        inside |= cells - out
    return inside


def screen(b):
    """ATASCII to the internal code screen memory holds."""
    c = b & 0x7F
    return (c + 0x40 if c < 0x20 else c - 0x20 if c < 0x60 else c) | (b & 0x80)


def c_header(art, row):
    out = ["/* generated by tools/title_art.py: the title art, drawn from screen row %d */" % row,
           "#define TITLE_END %d          /* the first row below it */" % (row + len(art)),
           "#define SNOW_LEFT %d          /* player 0's horizontal position */" % (48 + 4 * left(art)),
           "static const unsigned char title_art[] = {   /* row, column, length, screen codes */"]
    for r, line in enumerate(art):
        text = line.rstrip(b" ")
        col = len(text) - len(text.lstrip(b" "))
        if text:
            out.append("    %d, %d, %d, %s," % (row + r, col, len(text) - col,
                                               ", ".join("0x%02X" % screen(b) for b in text[col:])))
    out += ["    0xFF", "};"]
    return "\n".join(out)


def left(art):
    return min(c for _, c in strokes(art))


def s_include(art, row):
    inside = strokes(art)
    rows = sorted({r for r, _ in inside})
    first, last = rows[0], rows[-1]
    c0 = left(art)
    if max(c for _, c in inside) - c0 >= 8 * PLAYERS:
        sys.exit("title_art.py: the letters are wider than %d columns" % (8 * PLAYERS))
    n = last - first + 1
    if 4 * n > 128:
        sys.exit("title_art.py: the letters are taller than 32 rows")
    out = ["; generated by tools/title_art.py: which characters of each text row get the static",
           "SNOW_TOP  = %d          ; player byte of the first row: 2 scan lines a byte, row 0 at byte 16"
           % (16 + 4 * (row + first)),
           "SNOW_ROWS = %d" % n,
           "snow_mask:              ; player 0's rows, then player 1's, ...; bit 7 = its left column"]
    for p in range(PLAYERS):
        masks = []
        for r in range(first, last + 1):
            m = 0
            for b in range(8):
                if (r, c0 + 8 * p + b) in inside:
                    m |= 0x80 >> b
            masks.append("$%02X" % m)
        out.append("        .byte " + ", ".join(masks))
    return "\n".join(out)


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("c", "s"):
        sys.exit(__doc__)
    art = load(sys.argv[3])
    row = int(sys.argv[2])
    if row + len(art) > 24:
        sys.exit("title_art.py: the art runs off the screen")
    print(c_header(art, row) if sys.argv[1] == "c" else s_include(art, row))


main()
