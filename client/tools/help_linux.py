#!/usr/bin/env python3
"""The linux client's instruction pages as a C header, build/linux/help_tab.h (the Makefile's rule).

Usage:
    help_linux.py OUT.h HELP01.TXT HELP02.TXT ...

A page is plain ASCII: the first line is its heading, then at most 17 lines of at most 52 characters. Pages are
numbered 01, 02... with no gaps. a backslash shows as the yen sign, as the server's text does. The header has
help_pages (the count) and help_text[page][line], strings, "" for a blank line."""
import re
import sys

WIDTH, LINES = 52, 18


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out, paths = sys.argv[1], sys.argv[2:]
    for n, path in enumerate(paths, 1):
        if not re.search(r"HELP%02d\.TXT$" % n, path):
            sys.exit("%s: expected HELP%02d.TXT (pages are numbered from 01 with no gaps)" % (path, n))
    pages = []
    for path in paths:
        lines = open(path).read().split("\n")
        while lines and not lines[-1]:
            lines.pop()
        if len(lines) > LINES:
            sys.exit("%s: over %d lines" % (path, LINES))
        for i, line in enumerate(lines):
            if len(line) > WIDTH:
                sys.exit("%s:%d: over %d characters" % (path, i + 1, WIDTH))
            if not all(" " <= ch <= "~" for ch in line):
                sys.exit("%s:%d: not printable ASCII" % (path, i + 1))
        pages.append(lines)
    c = ["/* generated by tools/help_linux.py: the instruction pages */",
         "#define HELP_PAGES %d" % len(pages), "#define HELP_LINES %d" % LINES, "#define HELP_WIDTH %d" % WIDTH,
         "static const char *const help_text[HELP_PAGES][HELP_LINES] = {"]
    for lines in pages:
        c.append("    {")
        for line in lines:
            c.append('        "%s",' % line.replace("\\", "\\\\").replace('"', '\\"'))
        c.append("    },")
    c.append("};")
    open(out, "w").write("\n".join(c) + "\n")


main()
